// Guardamos el texto original del HTML en data-original
document.addEventListener("DOMContentLoaded", () => {
  document.querySelectorAll('[data-translate]').forEach(el => {
    const attr = el.getAttribute('data-translate-attr');
    if (attr) {
      el.dataset.original = el.getAttribute(attr); // guardar placeholder, title, etc.
    } else {
      el.dataset.original = el.innerHTML; // guardar contenido HTML original
    }
  });

  const saved = localStorage.getItem('lang') || 'es';
  translatePage(saved);
});

/* Traducción ─ soporte texto, <title>, <meta>, y atributos */
function translatePage(lang) {
  localStorage.setItem("lang", lang);

  // <title> especial
  const titleEl = document.querySelector('title[data-translate]');
  if (titleEl) {
    const k = titleEl.getAttribute('data-translate');
    if (lang === 'es') {
      document.title = titleEl.dataset.original || titleEl.innerHTML;
    } else if (textos[lang][k]) {
      document.title = textos[lang][k];
    }
  }

  // <meta name="description">
  document.querySelectorAll('meta[data-translate]').forEach(meta => {
    const key = meta.getAttribute('data-translate');
    if (lang === 'es') {
      if (meta.dataset.original) {
        meta.setAttribute('content', meta.dataset.original);
      }
    } else if (textos[lang][key]) {
      // Guardar original si no está
      if (!meta.dataset.original) {
        meta.dataset.original = meta.getAttribute('content');
      }
      meta.setAttribute('content', textos[lang][key]);
    }
  });

  // Resto de elementos
  document.querySelectorAll('[data-translate]').forEach(el => {
    if (el.tagName.toLowerCase() === 'title' || el.tagName.toLowerCase() === 'meta') return;

    const key = el.getAttribute('data-translate');
    const attr = el.getAttribute('data-translate-attr');

    if (lang === 'es') {
      // Restaurar texto original
      if (attr) {
        if (el.dataset.original) el.setAttribute(attr, el.dataset.original);
      } else {
        if (el.dataset.original) el.innerHTML = el.dataset.original;
      }
    } else {
      const val = textos[lang][key];
      if (!val) {
        console.warn(`[i18n] Falta clave "${key}" para lang "${lang}"`);
        return;
      }
      if (attr) {
        el.setAttribute(attr, val);
      } else {
        el.innerHTML = val;
      }
    }
  });

  document.documentElement.setAttribute('lang', lang);
}

